import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const {chromium} = createRequire(import.meta.url)('playwright');
const [handoffPath, stopPath, outputDir, distro='Ubuntu-26.04'] = process.argv.slice(2);
if (!handoffPath || !stopPath || !outputDir) throw new Error('usage: browser_qa HANDOFF STOP OUTPUT [WSL_DISTRO]');
const delay = ms => new Promise(resolve => setTimeout(resolve,ms));
const steps=[];
let browser;
try {
  for(let attempt=0;attempt<100 && !fs.existsSync(handoffPath);attempt++) await delay(100);
  const fixture=JSON.parse(fs.readFileSync(handoffPath,'utf8'));
  assert.match(fixture.token_file,/^\/tmp\/xmqr-admin-lab-[^/]+\/access\.token$/);
  const tokenPath=process.platform==='win32' ? `\\\\wsl.localhost\\${distro}${fixture.token_file.replaceAll('/','\\')}` : fixture.token_file;
  const token=fs.readFileSync(tokenPath,'utf8').trim();
  assert.equal(token.length,64);
  fs.mkdirSync(outputDir,{recursive:true});
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage();
  const failures=[];
  let expectedUnauthorized=false;
  page.on('pageerror', () => failures.push('unhandled browser exception'));
  page.on('console', event => { if(event.type()==='error' && !expectedUnauthorized) failures.push('unexpected browser console error'); });
  await page.goto(fixture.url);
  await page.waitForLoadState('networkidle');
  await page.locator('#login-section').waitFor({state:'visible'});
  assert.equal(await page.locator('#workspace').isVisible(),false);
  steps.push('authenticated shell has no private data before login');
  expectedUnauthorized=true;
  await page.locator('#token').fill((token[0]==='0'?'1':'0')+token.slice(1));
  await page.getByRole('button',{name:'Desbloquear painel'}).click();
  await page.getByText('Token recusado ou origem não autorizada.',{exact:false}).waitFor();
  await page.waitForLoadState('networkidle');
  expectedUnauthorized=false;
  steps.push('bad token refused with guidance');
  await page.locator('#token').fill(token);
  await page.getByRole('button',{name:'Desbloquear painel'}).click();
  await page.getByRole('heading',{name:'Broker pronto para operar'}).waitFor();
  assert.equal(await page.locator('[data-metric="xmqr_connections_active"]').textContent(),'1');
  assert.equal(await page.locator('[data-metric="xmqr_retained_messages"]').textContent(),'1');
  assert.equal(await page.locator('#token').inputValue(),'');
  steps.push('good token shows real broker/MQTT aggregates');
  await page.screenshot({path:path.join(outputDir,'desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Operações administrativas',exact:true}).click();
  await page.getByRole('heading',{name:'Operações pelo terminal'}).waitFor();
  assert.equal(await page.locator('#overview').isVisible(),false);
  await page.getByRole('button',{name:'Sobre e próximos passos'}).click();
  await page.getByRole('heading',{name:'Uma ferramenta, três responsabilidades'}).waitFor();
  await page.getByRole('button',{name:'Visão geral',exact:true}).click();
  await page.getByRole('button',{name:'Atualizar leitura'}).click();
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('[data-metric="xmqr_retained_messages"]').textContent(),'1');
  steps.push('sidebar and refresh are functional');
  const storage=await page.evaluate(() => ({local:localStorage.length,session:sessionStorage.length,url:location.href,overflow:document.documentElement.scrollWidth>innerWidth}));
  assert.equal(storage.local,0);assert.equal(storage.session,0);assert.equal(storage.overflow,false);
  assert.equal(storage.url,fixture.url+'/');
  steps.push('no token persistence/query or desktop horizontal overflow');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(outputDir,'mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth>innerWidth),false);
  steps.push('mobile layout without horizontal overflow');
  await page.getByRole('button',{name:'Sair do painel'}).click();
  assert.equal(await page.locator('#workspace').isVisible(),false);
  assert.equal(await page.locator('#token').inputValue(),'');
  assert.equal(await page.locator('[data-metric="xmqr_connections_active"]').textContent(),'—');
  await page.reload();await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('#workspace').isVisible(),false);
  steps.push('logout/reload clears access and aggregates');
  assert.equal(failures.length,0,'unexpected browser errors');
  steps.push('no unhandled exceptions or unexpected console errors');
  fs.writeFileSync(path.join(outputDir,'browser.json'),JSON.stringify({status:'PASS',count:steps.length,steps,backend:'real test-owned WSL broker/admin',browser:'headless Chromium/Playwright JS',synthetic_view_data:false,real_operator_data:false},null,2)+'\n');
  console.log('ADMIN_BROWSER_PASS',steps.length);
} finally {
  if(browser) await browser.close();
  fs.writeFileSync(stopPath,'stop\n');
  const closed=handoffPath.replace(/\.json$/,'.closed.json');
  for(let attempt=0;attempt<100 && !fs.existsSync(closed);attempt++) await delay(100);
  if(!fs.existsSync(closed)) throw new Error('test fixture cleanup was not confirmed');
}
