// QA do browser contra servidor/CLI próprios; MQTT real é gate separado.
import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const {chromium} = createRequire(import.meta.url)('playwright');
const [handoff, stop, output] = process.argv.slice(2);
if(!handoff || !stop || !output) throw new Error('uso: HANDOFF STOP PASTA_NOVA');
const delay = ms => new Promise(resolve=>setTimeout(resolve,ms));
for(let n=0; n<100 && !fs.existsSync(handoff); n++) await delay(200);
const fixture=JSON.parse(fs.readFileSync(handoff,'utf8'));
assert.match(fixture.token_file,/^\/var\/tmp\/xmqr-admin-a23-browser-[^/]+\/access\.token$/);
const tokenPath=process.platform==='win32' ? `\\\\wsl.localhost\\Ubuntu-26.04${fixture.token_file.replaceAll('/','\\')}` : fixture.token_file;
const token=fs.readFileSync(tokenPath,'utf8').trim();
assert.match(token,/^[a-f0-9]{64}$/);
fs.mkdirSync(output,{recursive:true});
const rows=[];const failures=[];
let browser;
try {
  browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
  page.on('pageerror',()=>failures.push('excecao no browser'));
  page.on('dialog',async dialog=>{failures.push('script remoto executou dialog');await dialog.dismiss();});
  await page.goto(fixture.url);
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('#workspace').isVisible(),false);
  await page.locator('#token').fill('a'.repeat(64)===token?'b'.repeat(64):'a'.repeat(64));
  await page.getByRole('button',{name:'Desbloquear painel'}).click();
  await page.locator('#login-message.error').waitFor();
  rows.push('token invalido recusado');
  await page.locator('#token').fill(token);
  await page.getByRole('button',{name:'Desbloquear painel'}).click();
  await page.locator('#workspace').waitFor({state:'visible'});
  assert.equal(await page.locator('#token').inputValue(),'');
  rows.push('login sem persistir token');
  await page.getByRole('button',{name:'Console MQTT',exact:true}).click();
  await page.locator('#subscribe-topic').fill('a23/#');
  await page.locator('#subscribe-qos').selectOption('1');
  await page.locator('#connect').click();
  await page.waitForFunction(()=>document.querySelector('#connection-state').textContent==='Assinatura ativa');
  await page.waitForFunction(()=>document.querySelectorAll('#messages .message-item').length>=2);
  assert.match(await page.locator('#messages').innerText(),/<img src=x onerror=alert\(1\)>/);
  assert.equal(await page.locator('#messages img').count(),0);
  rows.push('assinatura ativa apos SUBACK e conteudo remoto sem HTML');
  await page.locator('#publish-topic').fill('a23/value');
  await page.locator('#publish-payload').fill('{"temperature":24.6,"humidity":58.2}');
  await page.locator('#publish-qos').selectOption('1');
  await page.locator('#publish').click();
  await page.waitForFunction(()=>document.querySelector('#messages').textContent.includes('"temperature":24.6'));
  rows.push('publicacao confirmada pela API');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
  await page.locator('#message-search').fill('temperature');
  assert.equal(await page.locator('#messages .message-item').count(),1);
  await page.locator('#message-search').fill('');
  await page.locator('#pause').click();
  assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
  await page.locator('#pause').click();
  rows.push('busca e pausa visual funcionais');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  rows.push('layout mobile sem overflow');
  await page.locator('#clear').click();
  assert.equal(await page.locator('#messages .message-item').count(),0);
  await delay(3300);
  assert.equal(await page.locator('#messages .message-item').count(),0);
  rows.push('limpeza local nao reapresenta backlog');
  await page.locator('#logout').click();
  await page.locator('#login-section').waitFor({state:'visible'});
  assert.equal(await page.locator('#messages .message-item').count(),0);
  assert.equal(await page.locator('#publish-payload').inputValue(),'');
  const storage=await page.evaluate(()=>[localStorage.length,sessionStorage.length]);
  assert.deepEqual(storage,[0,0]);
  const backend=await page.request.get(fixture.url+'/api/mqtt',{headers:{Authorization:'Bearer '+token}});
  assert.equal((await backend.json()).status,'disconnected');
  rows.push('logout encerra assinatura e limpa acesso/dados');
  assert.deepEqual(failures,[]);
  rows.push('sem excecoes ou scripts remotos');
  fs.writeFileSync(path.join(output,'browser.json'),JSON.stringify({status:'PASS',steps:rows,backend:'servidor real A23 + fake CLI proprio; gate MQTT real separado',browser:'Chromium/Playwright',operator_data:false},null,2));
  console.log('A23_BROWSER_PASS',rows.length);
} catch(error) {
  fs.writeFileSync(path.join(output,'browser.json'),JSON.stringify({status:'FAIL',steps:rows,error:String(error)},null,2));
  throw error;
} finally {
  if(browser) await browser.close();
  fs.writeFileSync(stop,'stop');
}
